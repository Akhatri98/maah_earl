"""The eval scenario set -- ~20 parametric perturbations of the validated truss. [Track A, Sprint 5A]

plan.md, Validation: "~20 scenarios are generated by parametrically perturbing
the validated truss (resize a member, remove one, add/shift a load). Each
scenario's correct outcome is computed offline with the validated solver --
that's ground truth."

This module is the perturbation half. It owns no physics and no judgement: it
produces (before, after) `DependencyGraph` pairs and nothing else. Ground
truth is `earl.analysis.scoreboard.ground_truth()` on the after-graph -- the
validated solver over every load case plus Biject -- never a number written
down here.

## The base design

Track B's demo structure: the published Case 1 optimum with a uniform 10 %
design margin (`DEMO_AREAS_IN2`), 100 kip down at n2 and n4. Every member
starts safe, m5 governs at SF 1.100 and m7 is next at 1.489. That headroom is
what makes the set discriminating -- see "Why these scenarios" below.

## Every scenario graph is walkable

`build_ten_bar_graph()` emits ZERO edges and targets "benchmark", which
matches no entity, so a walk over it reaches nothing (sprint3a_handover.md
section 4). Every scenario built here therefore carries:

  * the full node-sharing TOPOLOGY edge set (`benchmark.topology_edges()`),
    the same set Track A's `graph_builder` derives from Onshape mates;
  * LOAD_PATH edges from a load change's node to the members incident on it,
    so a load scenario seeds on a real entity and spreads through topology;
  * VARIABLE_REF edges from a changed variable to every member it drives,
    matching `graph_builder.variable_ref_edges()`;
  * a `change.target_id` naming a real member, node or edge source.

`affected_member_ids` is deliberately left EMPTY. The fixed walk populates it
(`pipeline.run_pipeline` -> `walk_and_apply`), which is the whole claim under
test; a scenario that shipped its own affected set would be marking its own
homework, and would hand the baseline agent the traversal it is supposed to
lack.

## Why these scenarios

A scenario set can flatter either agent by accident, so the mix is chosen
against two specific failure modes:

  * "ESCALATE EVERYTHING" MUST LOSE.  If no change is ever genuinely safe, a
    baseline that flags all ten members every time scores zero dropped
    dominoes -- a perfect headline number (sprint3a_handover.md section 3).
    Roughly half the set is therefore SAFE, where that policy costs ten false
    alarms apiece.
  * "CHECK WHAT YOU TOUCHED" MUST LOSE.  In most unsafe scenarios the failing
    member is NOT the edited one -- thinning m3 fails m5, thickening m1 fails
    m5, moving a load fails m2/m6/m10. An agent that reasons only about the
    entity named in the change drops those dominoes, which is exactly the gap
    plan.md is built to measure.

Both properties are asserted in `tests/test_scenarios.py` against the real
solver, not assumed here.
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace

from ..analysis.benchmark import (
    CONNECTIVITY,
    DEMO_AREAS_IN2,
    KIP,
    MEMBER_IDS,
    build_ten_bar_graph,
    topology_edges,
)
from ..contracts import (
    ChangeEvent,
    ChangeKind,
    DependencyGraph,
    Edge,
    EdgeKind,
    OnshapeRef,
    PointLoad,
)

BASE_LOADS_KIPS: tuple[float, float] = (100.0, 100.0)
LOAD_CASE_ID = "lc_benchmark"

# The Onshape document the demo truss lives in. Scenarios are evaluated
# offline, but each one still names the branch it WOULD be evaluated in, so
# the ECN's "sandbox, not main" claim reads the same in the eval as in a live
# run (plan.md, stage 1).
EVAL_DOCUMENT = OnshapeRef(
    document_id="74352477fea92ae1dadf61d6",
    workspace_id="7121b248aa290fdccdc1afa6",
    element_id="72f445c1fb5399de58418375",
)


def members_at(node_id: str) -> list[str]:
    """Member ids incident on a node, in m1..m10 order."""
    return [mid for mid, a, b in CONNECTIVITY if node_id in (a, b)]


def base_area_in2(member_id: str) -> float:
    """The member's area in the unperturbed design."""
    return DEMO_AREAS_IN2[MEMBER_IDS.index(member_id)]


def _source_for(scenario_id: str) -> OnshapeRef:
    return replace(EVAL_DOCUMENT, branch_name=f"earl-eval-{scenario_id}")


# --------------------------------------------------------------------------
# The scenario
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class ScenarioGraphs:
    """One scenario, built: the design before the change and after it."""

    before: DependencyGraph
    after: DependencyGraph


@dataclass(frozen=True)
class Scenario:
    """A declarative perturbation of the base design.

    The constructors below populate exactly one perturbation; `build()`
    applies it to a fresh copy of the base design, so a scenario is reusable
    and no two runs share mutable state.
    """

    id: str
    kind: ChangeKind
    description: str
    target_id: str
    value_before: str | None = None
    value_after: str | None = None

    # Perturbations -- see the constructors below.
    areas_in2: dict[str, float] = field(default_factory=dict)   # member -> absolute area
    removed_member: str | None = None
    added_loads: tuple[PointLoad, ...] = ()
    moved_load: tuple[str, str] | None = None                   # (load id, destination node)
    loads_kips: tuple[float, float] | None = None               # replaces the base n2/n4 loads
    load_path_nodes: tuple[str, ...] = ()                       # seed LOAD_PATH edges from these
    variable_drives_members: bool = False                       # seed VARIABLE_REF edges

    # -- construction -------------------------------------------------------

    def _change(self) -> ChangeEvent:
        return ChangeEvent(
            id=f"chg-{self.id}",
            kind=self.kind,
            description=self.description,
            target_id=self.target_id,
            value_before=self.value_before,
            value_after=self.value_after,
        )

    def _edges(self, graph: DependencyGraph) -> list[Edge]:
        """Topology for the whole truss, plus whatever the change itself hangs
        off: a load change seeds from its node, a variable edit from the
        variable. Both mirror what `graph_builder` emits for a real Onshape
        read."""
        edges = topology_edges()
        seen_load_path: set[tuple[str, str]] = set()
        for node_id in self.load_path_nodes:
            for member_id in members_at(node_id):
                if (node_id, member_id) not in seen_load_path:
                    seen_load_path.add((node_id, member_id))
                    edges.append(Edge(node_id, member_id, EdgeKind.LOAD_PATH))
        if self.variable_drives_members:
            edges.extend(
                Edge(self.target_id, m.id, EdgeKind.VARIABLE_REF) for m in graph.members
            )
        return edges

    def _graph(self, *, after: bool, graph_id: str) -> DependencyGraph:
        areas = [
            self.areas_in2.get(mid, base) if after else base
            for mid, base in zip(MEMBER_IDS, DEMO_AREAS_IN2)
        ]
        loads = self.loads_kips if (after and self.loads_kips) else BASE_LOADS_KIPS
        graph = build_ten_bar_graph(
            areas_in2=areas, loads_kips=loads, graph_id=graph_id, change=self._change()
        )
        graph.source = _source_for(self.id)

        if after and self.removed_member is not None:
            graph.members = [m for m in graph.members if m.id != self.removed_member]
            graph.sections = [
                s for s in graph.sections if s.id != f"sec_{self.removed_member}"
            ]
        if after and self.added_loads:
            graph.load_cases[0].point_loads.extend(self.added_loads)
        if after and self.moved_load is not None:
            load_id, destination = self.moved_load
            for load in graph.load_cases[0].point_loads:
                if load.id == load_id:
                    load.node_id = destination

        graph.edges = self._edges(graph)
        graph.validate()
        return graph

    def build(self) -> ScenarioGraphs:
        """The (before, after) pair. `affected_member_ids` is empty on both --
        the fixed walk fills it, not this module."""
        return ScenarioGraphs(
            before=self._graph(after=False, graph_id=f"graph-{self.id}-before"),
            after=self._graph(after=True, graph_id=f"graph-{self.id}"),
        )


# --------------------------------------------------------------------------
# Constructors -- one per change kind the plan names
# --------------------------------------------------------------------------

def resize(scenario_id: str, member_id: str, area_after_in2: float) -> Scenario:
    """FEATURE_EDIT: one member's cross-section is set to a new area."""
    before = base_area_in2(member_id)
    verb = "Reduced" if area_after_in2 < before else "Increased"
    return Scenario(
        id=scenario_id,
        kind=ChangeKind.FEATURE_EDIT,
        description=(
            f"{verb} cross-section of member {member_id} from "
            f"{before:g} in^2 to {area_after_in2:g} in^2"
        ),
        target_id=member_id,
        value_before=f"{before:g} in^2",
        value_after=f"{area_after_in2:g} in^2",
        areas_in2={member_id: area_after_in2},
    )


def scale(scenario_id: str, member_id: str, factor: float) -> Scenario:
    """FEATURE_EDIT expressed as a factor of the member's design area."""
    return resize(scenario_id, member_id, round(base_area_in2(member_id) * factor, 4))


def remove(scenario_id: str, member_id: str) -> Scenario:
    """MEMBER_REMOVED: the member is deleted from the assembly.

    The member is gone from `graph.members` in the after-state, so the walk
    seeds on an id that is no longer an entity -- which is the truth, and
    which `walker.seed_ids` accepts for this change kind. Its TOPOLOGY edges
    are kept so the walk still reaches the neighbours that now carry its
    load; `DependencyGraph.validate()` admits them because the removed id is
    the change target.
    """
    return Scenario(
        id=scenario_id,
        kind=ChangeKind.MEMBER_REMOVED,
        description=(
            f"Removed member {member_id} ({base_area_in2(member_id):g} in^2) "
            "from the assembly"
        ),
        target_id=member_id,
        value_before=f"{base_area_in2(member_id):g} in^2",
        value_after="removed",
        removed_member=member_id,
    )


def add_load(
    scenario_id: str,
    node_id: str,
    *,
    down_kips: float = 0.0,
    east_kips: float = 0.0,
) -> Scenario:
    """LOAD_ADDED: a new point load appears at a node.

    `down_kips` is a downward (-Y) load, `east_kips` a lateral (+X) one. The
    change targets the NODE, which is a real graph entity, and LOAD_PATH edges
    run from it to every member framing into it.
    """
    parts = []
    if down_kips:
        parts.append(f"{down_kips:g} kip downward")
    if east_kips:
        parts.append(f"{east_kips:g} kip lateral (+X)")
    if not parts:
        raise ValueError(f"{scenario_id}: add_load needs a non-zero load")
    return Scenario(
        id=scenario_id,
        kind=ChangeKind.LOAD_ADDED,
        description=f"Added a {' and '.join(parts)} point load at node {node_id}",
        target_id=node_id,
        value_before="no load at this node",
        value_after=" and ".join(parts),
        added_loads=(
            PointLoad(
                id=f"p_{node_id}_added",
                node_id=node_id,
                fx=east_kips * KIP,
                fy=-down_kips * KIP,
            ),
        ),
        load_path_nodes=(node_id,),
    )


def move_load(scenario_id: str, load_id: str, from_node: str, to_node: str) -> Scenario:
    """LOAD_MOVED: an existing point load is relocated to another node.

    The change targets the DESTINATION node, and LOAD_PATH edges run from it
    to the members framing into either end of the move -- both sets genuinely
    carry redistributed load, which is what `EdgeKind.LOAD_PATH` means.
    """
    return Scenario(
        id=scenario_id,
        kind=ChangeKind.LOAD_MOVED,
        description=(
            f"Moved the point load {load_id} from node {from_node} to node {to_node}"
        ),
        target_id=to_node,
        value_before=f"at {from_node}",
        value_after=f"at {to_node}",
        moved_load=(load_id, to_node),
        load_path_nodes=(to_node, from_node),
    )


def edit_load_variable(
    scenario_id: str, before_kips: float, after_kips: float
) -> Scenario:
    """VARIABLE_EDIT on the design load, applied at both loaded nodes.

    The variable-table edit is the pipeline's primary change signal
    (`ingestion/benchmark.py`, VARIABLE_DRIVES), so the set carries it as well
    as the feature edits.
    """
    return Scenario(
        id=scenario_id,
        kind=ChangeKind.VARIABLE_EDIT,
        description=(
            f"Design load variable changed from {before_kips:g} kip to "
            f"{after_kips:g} kip at both loaded nodes"
        ),
        target_id="designLoad",
        value_before=f"{before_kips:g} kip",
        value_after=f"{after_kips:g} kip",
        loads_kips=(after_kips, after_kips),
        variable_drives_members=True,
    )


def edit_area_variable(scenario_id: str, factor: float) -> Scenario:
    """VARIABLE_EDIT on `barArea`, which drives every bar in the recorded
    Onshape document (`ingestion/benchmark.VARIABLE_DRIVES`)."""
    return Scenario(
        id=scenario_id,
        kind=ChangeKind.VARIABLE_EDIT,
        description=(
            f"barArea variable scaled to {factor:g}x, resizing every bar in "
            "the assembly"
        ),
        target_id="barArea",
        value_before="1x design area",
        value_after=f"{factor:g}x design area",
        areas_in2={
            mid: round(base_area_in2(mid) * factor, 4) for mid in MEMBER_IDS
        },
        variable_drives_members=True,
    )


# --------------------------------------------------------------------------
# The set
# --------------------------------------------------------------------------

# Twenty scenarios, every change kind plan.md names, ordered by kind so the
# demo can walk the list.
#
# Three properties are deliberate, and `tests/test_scenarios.py` pins all
# three against the real solver:
#
#   * ELEVEN UNSAFE, NINE SAFE at threshold 1.0. The safe nine are what make
#     "escalate everything" expensive -- ninety false alarms -- rather than a
#     free perfect score on the headline metric.
#   * EVERY CHANGE KIND APPEARS BOTH SAFE AND UNSAFE, so neither agent can do
#     well by learning "removals are bad" or "thickening is fine".
#   * IN TEN OF THE ELEVEN UNSAFE SCENARIOS THE FAILING MEMBER IS NOT THE ONE
#     THE CHANGE NAMES. s03 is the single exception, and it is kept so the
#     set cannot be accused of only ever rewarding a downstream answer.
#
# The truth values below are comments, not assertions: the harness computes
# ground truth from the solver every run, and the tests check these
# annotations still hold, so a solver change cannot quietly rewrite what the
# eval claims to measure.
SCENARIOS: tuple[Scenario, ...] = (
    # -- resize: thinner ---------------------------------------------------
    resize("s01-thin-m7-demo", "m7", 6.000),      # -> m5           (edited member passes)
    scale("s02-thin-m3", "m3", 0.75),             # -> m5           (edited member passes)
    scale("s03-thin-m1-severe", "m1", 0.1),       # -> m1, m5       (edited member fails too)
    scale("s04-thin-m4-half", "m4", 0.5),         # -> safe
    scale("s05-thin-m8-mild", "m8", 0.75),        # -> safe
    # -- resize: thicker ---------------------------------------------------
    # Adding material is not automatically safe: a stiffer member attracts
    # more load into the joint it shares with m5, which has no margin left.
    scale("s06-thicken-m1", "m1", 2.0),           # -> m5           (edited member passes)
    scale("s07-thicken-m8", "m8", 2.0),           # -> m5           (edited member passes)
    scale("s08-thicken-m5", "m5", 2.0),           # -> safe
    # -- removal -----------------------------------------------------------
    remove("s09-remove-m7", "m7"),                # -> m2, m5, m6, m10
    remove("s10-remove-m9", "m9"),                # -> m2, m5, m6, m7, m10
    remove("s11-remove-m2", "m2"),                # -> safe
    remove("s12-remove-m5", "m5"),                # -> safe (the governing member carried little)
    # -- load added --------------------------------------------------------
    add_load("s13-load-n1-down", "n1", down_kips=25.0),    # -> m6
    add_load("s14-load-n1-lateral", "n1", east_kips=50.0),  # -> m2, m10
    add_load("s15-load-n3-down", "n3", down_kips=50.0),     # -> safe
    add_load("s16-load-n2-lateral", "n2", east_kips=100.0),  # -> safe
    # -- load moved --------------------------------------------------------
    move_load("s17-move-n4-to-n1", "p_n4", "n4", "n1"),   # -> m2, m6, m10
    move_load("s18-move-n2-to-n3", "p_n2", "n2", "n3"),   # -> safe
    # -- variable edit -----------------------------------------------------
    edit_load_variable("s19-var-load-110", 100.0, 110.0),  # -> m5
    edit_area_variable("s20-var-area-110", 1.1),           # -> safe
)


def scenario_ids() -> list[str]:
    return [s.id for s in SCENARIOS]


def scenario(scenario_id: str) -> Scenario:
    for s in SCENARIOS:
        if s.id == scenario_id:
            return s
        # Allow the short prefix ("s01") so a demo can name one quickly.
        if s.id.split("-", 1)[0] == scenario_id:
            return s
    raise KeyError(f"no scenario {scenario_id!r}; known: {', '.join(scenario_ids())}")
